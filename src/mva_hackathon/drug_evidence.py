@dataclass
class DrugEvidenceConfig:
    """Configuration for Phase 3 drug-repurposing evidence engine."""

    # Candidate seed selection mode:
    # "query_panel": graph-derived Phase 3 query gene panel CSV (18_phase3_query_gene_panel.csv)
    # "mva_core": canonical MVA genes (7 core genes)
    # "mva_network": expert-curated reference panel of 13 genes (7 core + TP53, ATM, NF1, MAD2L2, AURKA, PLK1)
    # "passing_candidates": all genes with >= min_passing_variants
    # "custom": user-specified gene list
    seed_mode: str = "mva_network"
    custom_genes: list[str] = field(default_factory=list)
    query_panel_path: Path | None = None
    min_passing_variants: int = 1

    # HTTP client behavior
    request_timeout: float = 15.0
    max_retries: int = 3
    retry_backoff: float = 1.0
    polite_delay: float = 0.25  # seconds between HTTP requests
    user_agent: str = DEFAULT_USER_AGENT

    # Endpoint URLs
    open_targets_url: str = DEFAULT_OPEN_TARGETS_GQL_URL
    chembl_api_url: str = DEFAULT_CHEMBL_API_URL
    dgidb_url: str = DEFAULT_DGIDB_GQL_URL

    # Source enablement flags
    enable_open_targets: bool = True
    enable_chembl: bool = True
    enable_dgidb: bool = True

    # Offline / Fixture mode
    offline_mode: bool = False
    fixtures_dir: Path | None = None

    def __post_init__(self) -> None:
        if self.offline_mode:
            self.enable_open_targets = False
            self.enable_chembl = False
            self.enable_dgidb = False


class PoliteHttpClient:
    """Rate-limited, retry-aware HTTP client with fixture replay capability."""

    def __init__(self, config: DrugEvidenceConfig) -> None:
        self.config = config
        self.session = requests.Session()
        self.session.headers.update({"User-Agent": config.user_agent})

    def get(self, url: str, params: Mapping[str, Any] | None = None) -> requests.Response:
        return self._request_with_retry("GET", url, params=params)

    def post(
        self,
        url: str,
        json_data: Mapping[str, Any] | None = None,
    ) -> requests.Response:
        return self._request_with_retry("POST", url, json_data=json_data)

    def _request_with_retry(
        self,
        method: str,
        url: str,
        params: Mapping[str, Any] | None = None,
        json_data: Mapping[str, Any] | None = None,
    ) -> requests.Response:
        last_exception: Exception | None = None
        for attempt in range(1, self.config.max_retries + 1):
            try:
                if self.config.polite_delay > 0:
                    time.sleep(self.config.polite_delay)

                response = self.session.request(
                    method=method,
                    url=url,
                    params=params,
                    json=json_data,
                    timeout=self.config.request_timeout,
                )
                if response.status_code == 429:
                    wait_time = self.config.retry_backoff * (2 ** (attempt - 1))
                    logger.warning(
                        "Rate limited (429) at %s. Backing off for %.2fs (attempt %d/%d)...",
                        url,
                        wait_time,
                        attempt,
                        self.config.max_retries,
                    )
                    time.sleep(wait_time)
                    continue

                response.raise_for_status()
                return response

            except requests.RequestException as exc:
                last_exception = exc
                wait_time = self.config.retry_backoff * (2 ** (attempt - 1))
                logger.warning(
                    "HTTP %s to %s failed (attempt %d/%d): %s. Retrying in %.2fs...",
                    method,
                    url,
                    attempt,
                    self.config.max_retries,
                    exc,
                    wait_time,
                )
                time.sleep(wait_time)

        raise RuntimeError(
            f"Failed {method} request to {url} after {self.config.max_retries} attempts: {last_exception}"
        ) from last_exception


class OpenTargetsClient:
    """Client for Open Targets Platform GraphQL API v4."""

    def __init__(self, http_client: PoliteHttpClient, config: DrugEvidenceConfig) -> None:
        self.http_client = http_client
        self.config = config

    def search_target_ensembl_id(self, symbol: str) -> str | None:
        """Find the Ensembl gene ID for a given HGNC gene symbol."""
        query = """
        query SearchTarget($queryString: String!) {
          search(queryString: $queryString, entityNames: ["target"]) {
            hits {
              id
              name
              entity
            }
          }
        }
        """
        resp = self.http_client.post(
            self.config.open_targets_url,
            json_data={"query": query, "variables": {"queryString": symbol}},
        )
        data = _graphql_data(resp, "Open Targets").get("search", {})
        hits = data.get("hits", [])
        for hit in hits:
            if hit.get("name") == symbol and hit.get("entity") == "target":
                return hit.get("id")
        if hits and hits[0].get("entity") == "target":
            return hits[0].get("id")
        return None

    def fetch_target_drugs_and_safety(self, ensembl_id: str) -> dict[str, Any]:
        """Fetch known drugs, clinical candidates, tractability, and safety liabilities."""
        query = """
        query TargetDrugEvidence($ensemblId: String!) {
          target(ensemblId: $ensemblId) {
            id
            approvedSymbol
            approvedName
            tractability {
              label
              modality
              value
            }
            safetyLiabilities {
              event
              eventId
              effects {
                direction
                dosing
              }
              studies {
                name
                type
                description
              }
            }
            drugAndClinicalCandidates {
              count
              rows {
                id
                maxClinicalStage
                drug {
                  id
                  name
                  drugType
                  maximumClinicalStage
                  mechanismsOfAction {
                    rows {
                      mechanismOfAction
                      actionType
                      targets {
                        id
                        approvedSymbol
                      }
                    }
                  }
                  drugWarnings {
                    warningType
                    toxicityClass
                    description
                  }
                }
              }
            }
          }
        }
        """
        resp = self.http_client.post(
            self.config.open_targets_url,
            json_data={"query": query, "variables": {"ensemblId": ensembl_id}},
        )
        target = _graphql_data(resp, "Open Targets").get("target", {})
        return target or {}


class ChEMBLClient:
    """Client for ChEMBL v2.0 REST API."""

    def __init__(self, http_client: PoliteHttpClient, config: DrugEvidenceConfig) -> None:
        self.http_client = http_client
        self.config = config

    def fetch_target_mechanisms(self, symbol: str) -> list[dict[str, Any]]:
        """Fetch target records and their corresponding mechanism of action entries."""
        results: list[dict[str, Any]] = []
        target_url = f"{self.config.chembl_api_url}/target.json"
        resp = self.http_client.get(target_url, params={"target_synonym": symbol})
        targets = resp.json().get("targets", [])
        for target in targets:
            tid = target.get("target_chembl_id")
            target_type = target.get("target_type")
            pref_name = target.get("pref_name")
            if not tid:
                continue
            mech_url = f"{self.config.chembl_api_url}/mechanism.json"
            m_resp = self.http_client.get(mech_url, params={"target_chembl_id": tid})
            mechs = m_resp.json().get("mechanisms", [])
            for m in mechs:
                results.append({
                    "target_chembl_id": tid,
                    "target_pref_name": pref_name,
                    "target_type": target_type,
                    "molecule_chembl_id": m.get("molecule_chembl_id"),
                    "mechanism_of_action": m.get("mechanism_of_action"),
                    "action_type": m.get("action_type"),
                    "max_phase": m.get("max_phase"),
                    "direct_interaction": m.get("direct_interaction"),
                    "disease_efficacy": m.get("disease_efficacy"),
                    "mechanism_comment": m.get("mechanism_comment"),
                })
        return results


class DGIdbClient:
    """Client for DGIdb GraphQL API."""

    def __init__(self, http_client: PoliteHttpClient, config: DrugEvidenceConfig) -> None:
        self.http_client = http_client
        self.config = config

    def fetch_gene_interactions(self, symbols: list[str]) -> list[dict[str, Any]]:
        """Fetch drug-gene interactions for candidate genes via DGIdb GraphQL."""
        if not symbols:
            return []
        query = """
        query GetGeneInteractions($genes: [String!]!) {
          interactions(geneNames: $genes) {
            nodes {
              gene {
                name
                conceptId
              }
              drug {
                name
                conceptId
                approved
              }
              interactionScore
              interactionTypes {
                type
                directionality
              }
              sources {
                sourceDbName
              }
            }
          }
        }
        """
        resp = self.http_client.post(
            self.config.dgidb_url,
            json_data={"query": query, "variables": {"genes": symbols}},
        )
        nodes = _graphql_data(resp, "DGIdb").get("interactions", {}).get("nodes", [])
        return nodes or []


@dataclass
class DirectionalityEvaluation:
    """Evaluation of target modulation direction against patient variant mechanism."""

    fit_status: str  # "MECHANISTIC_HAZARD", "CONCORDANT_DIRECTION", "UNCERTAIN_DIRECTION", "OFF_TARGET_COMPENSATION"
    contradiction_flag: bool
    explanation: str
    pediatric_hazard_note: str


def evaluate_mechanism_directionality(
    gene_symbol: str,
    action_type: str | None,
    mechanism_desc: str | None,
    canonical_direction: str | None,
    therapeutic_direction: str | None,
    is_canonical_mva: bool,
) -> DirectionalityEvaluation:
    """Determine whether a drug's mechanism of action contradicts or aligns with the variant defect."""
    action = (action_type or "").strip().upper()
    mech = (mechanism_desc or "").strip().upper()
    direction = (canonical_direction or "").strip().upper()

    # Normalize action types into broad functional vectors
    is_inhibitor = any(
        kw in action or kw in mech
        for kw in ["INHIBITOR", "ANTAGONIST", "BLOCKER", "DOWNREGULATOR", "SUPPRESSOR", "DEGRADER", "RNAI"]
    )
    is_activator = any(
        kw in action or kw in mech
        for kw in ["ACTIVATOR", "AGONIST", "OPENER", "UPREGULATOR", "STABILIZER", "RECOMBINANT", "EXOGENOUS GENE"]
    )

    # 1. BUB1B / MAD1L1 / SAC checkpoint failure scenario:
    # Patient has loss-of-function / hypomorphic allele -> SAC is already impaired / weakened.
    # An INHIBITOR of BUB1B, MAD1L1, or SAC proteins directly aggravates premature mitotic exit,
    # escalating chromosome missegregation and cellular aneuploidy.
    if gene_symbol in ["BUB1B", "MAD1L1"] or "SAC" in direction or "CHECKPOINT" in direction:
        if is_inhibitor:
            return DirectionalityEvaluation(
                fit_status="MECHANISTIC_HAZARD",
                contradiction_flag=True,
                explanation=(
                    f"Direct mechanistic contradiction: Patient has LoF/hypomorphic {gene_symbol} with impaired SAC. "
                    f"Inhibition of {gene_symbol} ({action or 'INHIBITOR'}) accelerates premature mitotic exit "
                    "and exacerbates chromosome missegregation/aneuploidy."
                ),
                pediatric_hazard_note=(
                    "HIGH HAZARD: Mitotic checkpoint inhibition disrupts developmental mitosis and "
                    "increases risk of catastrophic chromosomal instability in growing tissues."
                ),
            )
        elif is_activator:
            return DirectionalityEvaluation(
                fit_status="CONCORDANT_DIRECTION",
                contradiction_flag=False,
                explanation=(
                    f"Mechanistically aligned: {gene_symbol} activator/stabilizer could theoretically compensate "
                    "for hypomorphic checkpoint signaling (biological hypothesis only)."
                ),
                pediatric_hazard_note="Experimental/unverified: Pediatric developmental safety unknown.",
            )

    # 2. Centrosome / Microtubule / Cohesin genes (CEP57, TRIP13, SLF2, SMC5, CENATAC):
    if gene_symbol in ["CEP57", "TRIP13", "SLF2", "SMC5", "CENATAC"]:
        if is_inhibitor:
            return DirectionalityEvaluation(
                fit_status="MECHANISTIC_HAZARD",
                contradiction_flag=True,
                explanation=(
                    f"Mechanistic contradiction: {gene_symbol} structural/checkpoint deficiency is worsened by "
                    f"pharmacological inhibition ({action or 'INHIBITOR'}), exacerbating mitotic spindle/cohesion failure."
                ),
                pediatric_hazard_note="HIGH HAZARD: Disruption of mitotic spindle pole/cohesion machinery in children.",
            )

    # 3. TP53 / DNA Damage / Tumor Suppressor genes:
    if gene_symbol == "TP53":
        if is_inhibitor:
            return DirectionalityEvaluation(
                fit_status="MECHANISTIC_HAZARD",
                contradiction_flag=True,
                explanation=(
                    "Severe hazard: TP53 inactivation/inhibition abrogates the p53-mediated aneuploidy surveillance "
                    "and senescence checkpoint, permissive of malignant transformation."
                ),
                pediatric_hazard_note="EXTREME HAZARD: Potentiates oncogenesis and eliminates aneuploid cell arrest.",
            )
        elif is_activator or "EXOGENOUS GENE" in mech or "STABILIZER" in mech:
            return DirectionalityEvaluation(
                fit_status="CONCORDANT_DIRECTION",
                contradiction_flag=False,
                explanation=(
                    "Concordant direction: Restoring or activating p53 surveillance eliminates cells carrying mosaic aneuploidy "
                    "(theoretical biological mechanism)."
                ),
                pediatric_hazard_note="Investigational: Requires strict monitoring of cellular apoptosis.",
            )

    # 4. Spindle Kinases (AURKA, PLK1) - downstream or synthetic mitotic lethality
    if gene_symbol in ["AURKA", "PLK1"]:
        if is_inhibitor:
            return DirectionalityEvaluation(
                fit_status="OFF_TARGET_COMPENSATION",
                contradiction_flag=False,
                explanation=(
                    f"{gene_symbol} inhibition selectively induces mitotic catastrophe in highly aneuploid/cancer cells. "
                    "However, in a child with systemic MVA, mitotic arrest carries severe whole-body toxicity."
                ),
                pediatric_hazard_note="SEVERE PEDIATRIC RISK: Bone marrow suppression, growth plate disruption, neurotoxicity.",
            )

    # Default fallback
    if is_inhibitor:
        return DirectionalityEvaluation(
            fit_status="UNCERTAIN_DIRECTION",
            contradiction_flag=False,
            explanation=f"Target inhibition ({action}) evaluated against candidate gene {gene_symbol}.",
            pediatric_hazard_note="Uncharacterized pediatric profile.",
        )
    elif is_activator:
        return DirectionalityEvaluation(
            fit_status="CONCORDANT_DIRECTION",
            contradiction_flag=False,
            explanation=f"Target activation ({action}) evaluated against candidate gene {gene_symbol}.",
            pediatric_hazard_note="Uncharacterized pediatric profile.",
        )
    else:
        return DirectionalityEvaluation(
            fit_status="UNCERTAIN_DIRECTION",
            contradiction_flag=False,
            explanation=f"Action type '{action or 'UNKNOWN'}' requires empirical directionality validation.",
            pediatric_hazard_note="Uncharacterized pediatric profile.",
        )


class DrugEvidencePipeline:
    """Orchestrates Phase 3 multi-source drug-repurposing evidence consolidation and safety review."""

    def __init__(self, config: DrugEvidenceConfig) -> None:
        self.config = config
        self.http_client = PoliteHttpClient(config)
        self.ot_client = OpenTargetsClient(self.http_client, config)
        self.chembl_client = ChEMBLClient(self.http_client, config)
        self.dgidb_client = DGIdbClient(self.http_client, config)
        self.panel_metadata: dict[str, dict[str, Any]] = {}

    def select_seed_genes(
        self,
        gene_matrix_df: pd.DataFrame,
        network_context_df: pd.DataFrame | None = None,
    ) -> list[str]:
        """Select controlled seed genes according to configured strategy."""
        all_matrix_genes = set(gene_matrix_df["SYMBOL"].dropna().astype(str).str.strip()) if not gene_matrix_df.empty else set()

        if self.config.seed_mode == "query_panel" and self.config.query_panel_path:
            p_path = Path(self.config.query_panel_path)
            if p_path.is_file():
                panel_df = pd.read_csv(p_path)
                query_genes: list[str] = []
                for _, r in panel_df.iterrows():
                    sym = str(r.get("QUERY_GENE", "")).strip()
                    if sym:
                        query_genes.append(sym)
                        self.panel_metadata[sym] = {
                            "GENE_CATEGORY": str(r.get("GENE_CATEGORY", "CANDIDATE")),
                            "SELECTION_SOURCE": str(r.get("SELECTION_SOURCE", "QUERY_PANEL")),
                            "EVIDENCE_NATURE": str(r.get("EVIDENCE_NATURE", "GRAPH_INDIRECT")),
                            "CONTROL_ROLE": str(r.get("CONTROL_ROLE", "NONE")),
                            "CONTROL_EXPECTATION": str(r.get("CONTROL_EXPECTATION", "NA")),
                            "IN_MVA_FOCUS_COMPONENT": bool(r.get("IN_MVA_FOCUS_COMPONENT") == True),
                            "MVA_GENE_CLASS": str(r.get("MVA_GENE_CLASS", "NONE")),
                            "GENE_NAME": str(r.get("GENE_NAME", "")),
                            "PATHWAY": str(r.get("PATHWAY", "")),
                            "BIOLOGICAL_ROLE": str(r.get("BIOLOGICAL_ROLE", "")),
                            "MVA_MECHANISM_LINK": str(r.get("MVA_MECHANISM_LINK", "")),
                            "CANONICAL_PATHWAY_DIRECTION": str(r.get("CANONICAL_PATHWAY_DIRECTION", "")),
                            "THERAPEUTIC_DIRECTIONALITY": str(r.get("THERAPEUTIC_DIRECTIONALITY", "")),
                        }
                return query_genes

        if self.config.seed_mode == "custom" and self.config.custom_genes:
            seeds = [g for g in self.config.custom_genes if g in all_matrix_genes or not all_matrix_genes]
            return sorted(set(seeds))

        if self.config.seed_mode == "mva_core":
            # Canonical MVA genes that exist in the candidate matrix
            seeds = [g for g in CANONICAL_MVA_SEEDS if g in all_matrix_genes]
            if not seeds:
                seeds = CANONICAL_MVA_SEEDS.copy()
            return sorted(set(seeds))

        if self.config.seed_mode == "mva_network":
            # Uses expert-curated reference panel of 13 seeds (7 core MVA + TP53, ATM, NF1, MAD2L2, AURKA, PLK1)
            # intersected with Phase 1 candidates
            available = [g for g in EXPANDED_MVA_NETWORK_SEEDS if g in all_matrix_genes]
            if network_context_df is not None and "HGNC_SYMBOL" in network_context_df.columns:
                passing_net = network_context_df[
                    network_context_df["TOTAL_PASSING_CANDIDATE_VARIANTS"] >= self.config.min_passing_variants
                ]["HGNC_SYMBOL"].tolist()
                for g in passing_net:
                    if g in EXPANDED_MVA_NETWORK_SEEDS and g not in available:
                        available.append(g)
            if not available:
                available = EXPANDED_MVA_NETWORK_SEEDS.copy()
            return sorted(set(available))

        if self.config.seed_mode == "passing_candidates":
            passing_df = gene_matrix_df[
                gene_matrix_df["TOTAL_PASSING_CANDIDATE_VARIANTS"] >= self.config.min_passing_variants
            ]
            return sorted(passing_df["SYMBOL"].dropna().unique().tolist())

        # Fallback to expanded set
        return sorted(set([g for g in EXPANDED_MVA_NETWORK_SEEDS if g in all_matrix_genes] or EXPANDED_MVA_NETWORK_SEEDS))

    def collect_evidence_for_seeds(
        self,
        seed_genes: list[str],
        gene_matrix_df: pd.DataFrame,
    ) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, dict[str, Any]]:
        """Collect and normalize drug evidence across Open Targets, ChEMBL, and DGIdb."""
        start_time = datetime.now(timezone.utc)
        provenance_sources: dict[str, Any] = {
            "open_targets": {"queried": False, "status": "disabled"},
            "chembl": {"queried": False, "status": "disabled"},
            "dgidb": {"queried": False, "status": "disabled"},
        }

        # Build gene context lookup from Phase 1 matrix and panel metadata
        gene_context: dict[str, dict[str, Any]] = {}
        for _, row in gene_matrix_df.iterrows():
            sym = str(row.get("SYMBOL", "")).strip()
            if sym:
                gene_context[sym] = {
                    "gene_name": str(row.get("GENE_NAME", "")),
                    "pathway": str(row.get("PATHWAY", "")),
                    "biological_role": str(row.get("BIOLOGICAL_ROLE", "")),
                    "mva_mechanism_link": str(row.get("MVA_MECHANISM_LINK", "")),
                    "canonical_direction": str(row.get("CANONICAL_PATHWAY_DIRECTION", "")),
                    "therapeutic_direction": str(row.get("THERAPEUTIC_DIRECTIONALITY", "")),
                    "passing_variants": int(row.get("TOTAL_PASSING_CANDIDATE_VARIANTS", 0)),
                    "compound_het_fit": bool(row.get("COMPOUND_HET_ARCHETYPE_FIT", False)),
                    "phase_gate_status": str(row.get("PHASE_GATE_STATUS", "")),
                }

        # Supplement context for genes absent from Phase 1 using panel metadata
        for sym, p_meta in self.panel_metadata.items():
            if sym not in gene_context:
                gene_context[sym] = {
                    "gene_name": p_meta.get("GENE_NAME", sym),
                    "pathway": p_meta.get("PATHWAY", "Spindle Assembly Checkpoint / Mitotic Cell Cycle"),
                    "biological_role": p_meta.get("BIOLOGICAL_ROLE", "MVA Causal Component"),
                    "mva_mechanism_link": p_meta.get("MVA_MECHANISM_LINK", "Canonical MVA"),
                    "canonical_direction": p_meta.get("CANONICAL_PATHWAY_DIRECTION", "DOWN (Checkpoint arrest failure)"),
                    "therapeutic_direction": p_meta.get("THERAPEUTIC_DIRECTIONALITY", "Compensate impaired checkpoint / promote chromosome stability"),
                    "passing_variants": 0,
                    "compound_het_fit": False,
                    "phase_gate_status": "PHASE1_ABSENT",
                }

        raw_records: list[dict[str, Any]] = []

        # 1. Open Targets Collection
        if self.config.enable_open_targets:
            provenance_sources["open_targets"]["queried"] = True
            provenance_sources["open_targets"]["status"] = "active"
            ot_drug_count = 0
            for gene in seed_genes:
                ens_id = self.ot_client.search_target_ensembl_id(gene)
                if not ens_id:
                    continue
                ot_data = self.ot_client.fetch_target_drugs_and_safety(ens_id)
                tractability_labels = [
                    t["label"] for t in ot_data.get("tractability", []) if t.get("value")
                ]
                safety_liabilities = [
                    s.get("event") for s in ot_data.get("safetyLiabilities", []) if s.get("event")
                ]
                candidates_data = ot_data.get("drugAndClinicalCandidates", {})
                for row in candidates_data.get("rows", []):
                    drug = row.get("drug", {})
                    drug_id = drug.get("id") or row.get("id")
                    drug_name = drug.get("name") or "UNNAMED_DRUG"
                    drug_type = drug.get("drugType") or "Small molecule"
                    max_stage = drug.get("maximumClinicalStage") or row.get("maxClinicalStage") or "PRECLINICAL"

                    mechs = drug.get("mechanismsOfAction", {}).get("rows", [])
                    action_type = mechs[0].get("actionType") if mechs else None
                    mech_desc = mechs[0].get("mechanismOfAction") if mechs else None

                    warnings = [
                        w.get("description") or w.get("warningType")
                        for w in drug.get("drugWarnings", [])
                        if w.get("description") or w.get("warningType")
                    ]

                    raw_records.append({
                        "TARGET_SYMBOL": gene,
                        "ENSEMBL_ID": ens_id,
                        "DRUG_NAME": drug_name.upper(),
                        "DRUG_ID": drug_id,
                        "EVIDENCE_SOURCE": "Open Targets",
                        "DRUG_TYPE": drug_type,
                        "MAX_CLINICAL_STAGE": max_stage,
                        "IS_APPROVED": "APPROVED" in str(max_stage).upper() or max_stage == "PHASE_4",
                        "ACTION_TYPE": action_type or "UNKNOWN",
                        "MECHANISM_OF_ACTION": mech_desc or "UNSPECIFIED",
                        "TRACTABILITY_SUMMARY": "; ".join(tractability_labels[:3]),
                        "SAFETY_LIABILITIES": "; ".join(safety_liabilities[:3]),
                        "DRUG_WARNINGS": "; ".join(warnings[:2]),
                        "CONFIDENCE_SCORE": 0.9 if "APPROVED" in str(max_stage).upper() else 0.7,
                    })
                    ot_drug_count += 1
            provenance_sources["open_targets"]["drug_candidates_retrieved"] = ot_drug_count

        # 2. ChEMBL Collection
        if self.config.enable_chembl:
            provenance_sources["chembl"]["queried"] = True
            provenance_sources["chembl"]["status"] = "active"
            chembl_drug_count = 0
            for gene in seed_genes:
                mechs = self.chembl_client.fetch_target_mechanisms(gene)
                for m in mechs:
                    mol_id = m.get("molecule_chembl_id")
                    action = m.get("action_type") or "UNKNOWN"
                    mech_desc = m.get("mechanism_of_action") or "UNSPECIFIED"
                    max_phase = m.get("max_phase")
                    stage_str = f"PHASE_{int(max_phase)}" if max_phase is not None else "PRECLINICAL"
                    if max_phase == 4:
                        stage_str = "APPROVED"

                    raw_records.append({
                        "TARGET_SYMBOL": gene,
                        "ENSEMBL_ID": None,
                        "DRUG_NAME": mol_id,  # ChEMBL ID acts as identifier
                        "DRUG_ID": mol_id,
                        "EVIDENCE_SOURCE": "ChEMBL",
                        "DRUG_TYPE": "Small molecule",
                        "MAX_CLINICAL_STAGE": stage_str,
                        "IS_APPROVED": max_phase == 4,
                        "ACTION_TYPE": action,
                        "MECHANISM_OF_ACTION": mech_desc,
                        "TRACTABILITY_SUMMARY": "ChEMBL Curated Target",
                        "SAFETY_LIABILITIES": "",
                        "DRUG_WARNINGS": m.get("mechanism_comment") or "",
                        "CONFIDENCE_SCORE": 0.85 if max_phase == 4 else 0.65,
                    })
                    chembl_drug_count += 1
            provenance_sources["chembl"]["mechanisms_retrieved"] = chembl_drug_count

        # 3. DGIdb Collection
        if self.config.enable_dgidb:
            provenance_sources["dgidb"]["queried"] = True
            provenance_sources["dgidb"]["status"] = "active"
            dgidb_nodes = self.dgidb_client.fetch_gene_interactions(seed_genes)
            dgidb_count = 0
            for node in dgidb_nodes:
                gene_sym = node.get("gene", {}).get("name")
                drug = node.get("drug", {})
                drug_name = drug.get("name")
                drug_id = drug.get("conceptId")
                approved = drug.get("approved", False)
                types = node.get("interactionTypes", [])
                action = types[0].get("type") if types else "interaction"
                directionality = types[0].get("directionality") if types else ""
                sources = [s.get("sourceDbName") for s in node.get("sources", []) if s.get("sourceDbName")]
                score = node.get("interactionScore") or 0.5

                raw_records.append({
                    "TARGET_SYMBOL": gene_sym,
                    "ENSEMBL_ID": None,
                    "DRUG_NAME": str(drug_name).upper(),
                    "DRUG_ID": drug_id,
                    "EVIDENCE_SOURCE": "DGIdb",
                    "DRUG_TYPE": "Small molecule / Biologic",
                    "MAX_CLINICAL_STAGE": "APPROVED" if approved else "INVESTIGATIONAL",
                    "IS_APPROVED": approved,
                    "ACTION_TYPE": f"{action} ({directionality})" if directionality else action,
                    "MECHANISM_OF_ACTION": f"DGIdb interaction curated from {', '.join(sources[:2])}",
                    "TRACTABILITY_SUMMARY": f"Sources: {', '.join(sources[:3])}",
                    "SAFETY_LIABILITIES": "",
                    "DRUG_WARNINGS": "",
                    "CONFIDENCE_SCORE": float(score) if score else 0.5,
                })
                dgidb_count += 1
            provenance_sources["dgidb"]["interactions_retrieved"] = dgidb_count

        # Build Normalized Drug Evidence Matrix
        matrix_rows: list[dict[str, Any]] = []
        for r in raw_records:
            sym = r["TARGET_SYMBOL"]
            ctx = gene_context.get(sym, {})
            is_mva = sym in CANONICAL_MVA_SEEDS

            dir_eval = evaluate_mechanism_directionality(
                gene_symbol=sym,
                action_type=r["ACTION_TYPE"],
                mechanism_desc=r["MECHANISM_OF_ACTION"],
                canonical_direction=ctx.get("canonical_direction"),
                therapeutic_direction=ctx.get("therapeutic_direction"),
                is_canonical_mva=is_mva,
            )

            matrix_rows.append({
                "TARGET_SYMBOL": sym,
                "ENSEMBL_ID": r.get("ENSEMBL_ID") or "",
                "DRUG_NAME": r["DRUG_NAME"],
                "DRUG_ID": r["DRUG_ID"] or "",
                "EVIDENCE_SOURCE": r["EVIDENCE_SOURCE"],
                "DRUG_TYPE": r["DRUG_TYPE"],
                "MAX_CLINICAL_STAGE": r["MAX_CLINICAL_STAGE"],
                "IS_APPROVED": bool(r["IS_APPROVED"]),
                "ACTION_TYPE": r["ACTION_TYPE"],
                "MECHANISM_OF_ACTION": r["MECHANISM_OF_ACTION"],
                "TARGET_PATHWAY": ctx.get("pathway", "Unassigned"),
                "MVA_MECHANISM_LINK": ctx.get("mva_mechanism_link", "Secondary Candidate"),
                "CANONICAL_PATHWAY_DIRECTION": ctx.get("canonical_direction", "UNKNOWN"),
                "THERAPEUTIC_DIRECTIONALITY": ctx.get("therapeutic_direction", "UNKNOWN"),
                "DIRECTIONALITY_FIT": dir_eval.fit_status,
                "CONTRADICTION_FLAG": dir_eval.contradiction_flag,
                "DIRECTIONALITY_EXPLANATION": dir_eval.explanation,
                "SAFETY_LIABILITIES": r["SAFETY_LIABILITIES"],
                "DRUG_WARNINGS": r["DRUG_WARNINGS"],
                "PEDIATRIC_HAZARD_NOTE": dir_eval.pediatric_hazard_note,
                "TRACTABILITY": r["TRACTABILITY_SUMMARY"],
                "SOURCE_CONFIDENCE_SCORE": r["CONFIDENCE_SCORE"],
                "RESEARCH_ONLY_DISCLAIMER": RESEARCH_ONLY_DISCLAIMER,
                "GENE_CATEGORY": self.panel_metadata.get(sym, {}).get("GENE_CATEGORY", "CORE_MVA_CAUSAL" if is_mva else "CANDIDATE"),
                "SELECTION_SOURCE": self.panel_metadata.get(sym, {}).get("SELECTION_SOURCE", "EXPERT_SEED" if is_mva else "PHASE1"),
                "EVIDENCE_NATURE": self.panel_metadata.get(sym, {}).get("EVIDENCE_NATURE", "KNOWN_GENE" if is_mva else "CANDIDATE"),
                "CONTROL_ROLE": self.panel_metadata.get(sym, {}).get("CONTROL_ROLE", "NONE"),
                "IN_MVA_FOCUS_COMPONENT": self.panel_metadata.get(sym, {}).get("IN_MVA_FOCUS_COMPONENT", False),
            })

        evidence_matrix_df = pd.DataFrame(matrix_rows)
        if evidence_matrix_df.empty:
            evidence_matrix_df = pd.DataFrame(columns=[
                "TARGET_SYMBOL", "ENSEMBL_ID", "DRUG_NAME", "DRUG_ID", "EVIDENCE_SOURCE",
                "DRUG_TYPE", "MAX_CLINICAL_STAGE", "IS_APPROVED", "ACTION_TYPE",
                "MECHANISM_OF_ACTION", "TARGET_PATHWAY", "MVA_MECHANISM_LINK",
                "CANONICAL_PATHWAY_DIRECTION", "THERAPEUTIC_DIRECTIONALITY",
                "DIRECTIONALITY_FIT", "CONTRADICTION_FLAG", "DIRECTIONALITY_EXPLANATION",
                "SAFETY_LIABILITIES", "DRUG_WARNINGS", "PEDIATRIC_HAZARD_NOTE",
                "TRACTABILITY", "SOURCE_CONFIDENCE_SCORE", "RESEARCH_ONLY_DISCLAIMER",
                "GENE_CATEGORY", "SELECTION_SOURCE", "EVIDENCE_NATURE",
                "CONTROL_ROLE", "IN_MVA_FOCUS_COMPONENT"
            ])

        # Build Safety & Directionality Ranking
        ranking_df = self._build_safety_ranking(evidence_matrix_df, gene_context)

        # Build Mechanism Action Map
        action_map_df = self._build_mechanism_action_map(seed_genes, gene_context, evidence_matrix_df)

        end_time = datetime.now(timezone.utc)

        ot_tot = len(evidence_matrix_df[evidence_matrix_df["EVIDENCE_SOURCE"] == "Open Targets"]) if not evidence_matrix_df.empty else 0
        chembl_tot = len(evidence_matrix_df[evidence_matrix_df["EVIDENCE_SOURCE"] == "ChEMBL"]) if not evidence_matrix_df.empty else 0
        dgidb_tot = len(evidence_matrix_df[evidence_matrix_df["EVIDENCE_SOURCE"] == "DGIdb"]) if not evidence_matrix_df.empty else 0

        genes_with_hits = sorted(evidence_matrix_df["TARGET_SYMBOL"].unique()) if not evidence_matrix_df.empty else []
        genes_zero_hits = [g for g in seed_genes if g not in genes_with_hits]

        per_gene_cov: dict[str, dict[str, int]] = {}
        for g in seed_genes:
            gsub = evidence_matrix_df[evidence_matrix_df["TARGET_SYMBOL"] == g] if not evidence_matrix_df.empty else pd.DataFrame()
            per_gene_cov[g] = {
                "Open Targets": len(gsub[gsub["EVIDENCE_SOURCE"] == "Open Targets"]) if not gsub.empty else 0,
                "ChEMBL": len(gsub[gsub["EVIDENCE_SOURCE"] == "ChEMBL"]) if not gsub.empty else 0,
                "DGIdb": len(gsub[gsub["EVIDENCE_SOURCE"] == "DGIdb"]) if not gsub.empty else 0,
                "total": len(gsub),
            }

        pos_sanity: dict[str, Any] = {}
        neg_sanity: dict[str, Any] = {}
        for g, meta in self.panel_metadata.items():
            role = meta.get("CONTROL_ROLE", "NONE")
            hits_count = per_gene_cov.get(g, {}).get("total", 0)
            if role == "POSITIVE":
                pos_sanity[g] = {
                    "drug_rows": hits_count,
                    "status": "PASS_HITS_FOUND" if hits_count > 0 else "WARNING_ZERO_HITS",
                }
            elif role == "NEGATIVE":
                neg_sanity[g] = {
                    "drug_rows": hits_count,
                    "status": "PASS_ZERO_HITS" if hits_count == 0 else "WARNING_UNEXPECTED_HITS",
                }

        seed_prov_desc = (
            f"Dynamically derived from query panel at {self.config.query_panel_path} ({len(seed_genes)} genes across multiple functional tiers)"
            if self.config.seed_mode == "query_panel"
            else (
                "Expert-curated 13-seed panel (7 core MVA + TP53, ATM, NF1, MAD2L2, AURKA, PLK1) intersected with Phase 1 candidates"
                if self.config.seed_mode == "mva_network"
                else f"Seed selection mode: {self.config.seed_mode}"
            )
        )

        provenance: dict[str, Any] = {
            "execution_timestamp_utc": end_time.isoformat(),
            "pipeline_version": "0.3.0",
            "seed_mode": self.config.seed_mode,
            "seed_provenance": seed_prov_desc,
            "query_panel_path": str(self.config.query_panel_path) if self.config.query_panel_path else "",
            "panel_category_counts": pd.Series([m.get("GENE_CATEGORY") for m in self.panel_metadata.values()]).value_counts().to_dict() if self.panel_metadata else {},
            "seed_genes_evaluated": seed_genes,
            "seed_genes_count": len(seed_genes),
            "genes_queried": seed_genes,
            "genes_with_zero_hits": genes_zero_hits,
            "total_drug_target_pairs_retrieved": len(evidence_matrix_df),
            "per_source_row_counts": {
                "Open Targets": ot_tot,
                "ChEMBL": chembl_tot,
                "DGIdb": dgidb_tot,
            },
            "per_gene_source_coverage": per_gene_cov,
            "positive_control_sanity": pos_sanity,
            "negative_control_sanity": neg_sanity,
            "sources_contacted": provenance_sources,
            "contradiction_count": int(evidence_matrix_df["CONTRADICTION_FLAG"].sum()) if not evidence_matrix_df.empty else 0,
            "mechanistic_hazard_count": int((evidence_matrix_df["DIRECTIONALITY_FIT"] == "MECHANISTIC_HAZARD").sum()) if not evidence_matrix_df.empty else 0,
            "offline_mode": self.config.offline_mode,
            "execution_duration_seconds": (end_time - start_time).total_seconds(),
            "ethical_and_regulatory_notice": {
                "disclaimer": RESEARCH_ONLY_DISCLAIMER,
                "regulatory_status": "Strictly research exploration; no drug evaluated in this pipeline is approved or recommended for clinical use in this patient.",
            },
        }

        return evidence_matrix_df, ranking_df, action_map_df, provenance

    def _build_safety_ranking(
        self,
        matrix_df: pd.DataFrame,
        gene_context: dict[str, dict[str, Any]],
    ) -> pd.DataFrame:
        """Aggregate drug evidence per unique drug-target pair and score safety/directionality tier."""
        if matrix_df.empty:
            return pd.DataFrame(columns=[
                "TARGET_SYMBOL", "DRUG_NAME", "AGGREGATED_SOURCES", "MAX_CLINICAL_STAGE",
                "APPROVED_ANY", "DIRECTIONALITY_FIT", "CONTRADICTION_FLAG",
                "SAFETY_TIER", "RESEARCH_PRIORITY_RANK", "DIRECTIONALITY_EXPLANATION",
                "PEDIATRIC_HAZARD_NOTE", "CLINICAL_RECOMMENDATION_STATUS",
                "RESEARCH_ONLY_DISCLAIMER", "GENE_CATEGORY", "SELECTION_SOURCE",
                "EVIDENCE_NATURE", "CONTROL_ROLE", "IN_MVA_FOCUS_COMPONENT"
            ])

        grouped = matrix_df.groupby(["TARGET_SYMBOL", "DRUG_NAME"], as_index=False)
        ranked_rows: list[dict[str, Any]] = []

        for (sym, drug_name), group in grouped:
            sources = sorted(group["EVIDENCE_SOURCE"].unique())
            max_stage = group["MAX_CLINICAL_STAGE"].iloc[0]
            for s in group["MAX_CLINICAL_STAGE"]:
                if "APPROVED" in str(s).upper() or s == "PHASE_4":
                    max_stage = "APPROVED"
                    break

            approved_any = bool(group["IS_APPROVED"].any())
            has_contradiction = bool(group["CONTRADICTION_FLAG"].any())
            has_hazard = (group["DIRECTIONALITY_FIT"] == "MECHANISTIC_HAZARD").any()

            if has_hazard or has_contradiction:
                fit_status = "MECHANISTIC_HAZARD"
                safety_tier = "TIER_4_CONTRAINDICATED_HAZARD"
                score = -100.0  # heavily penalized
            elif (group["DIRECTIONALITY_FIT"] == "CONCORDANT_DIRECTION").any():
                fit_status = "CONCORDANT_DIRECTION"
                safety_tier = "TIER_1_CONCORDANT_HYPOTHESIS"
                score = 50.0 + (30.0 if approved_any else 10.0) + (10.0 * len(sources))
            elif (group["DIRECTIONALITY_FIT"] == "OFF_TARGET_COMPENSATION").any():
                fit_status = "OFF_TARGET_COMPENSATION"
                safety_tier = "TIER_2_OFF_TARGET_COMPENSATION"
                score = 30.0 + (20.0 if approved_any else 5.0)
            else:
                fit_status = "UNCERTAIN_DIRECTION"
                safety_tier = "TIER_3_UNCERTAIN_DIRECTIONALITY"
                score = 10.0 + (10.0 if approved_any else 0.0)

            p_meta = self.panel_metadata.get(sym, {})
            cat = p_meta.get("GENE_CATEGORY") or (group["GENE_CATEGORY"].iloc[0] if "GENE_CATEGORY" in group.columns else "")
            src = p_meta.get("SELECTION_SOURCE") or (group["SELECTION_SOURCE"].iloc[0] if "SELECTION_SOURCE" in group.columns else "")
            nature = p_meta.get("EVIDENCE_NATURE") or (group["EVIDENCE_NATURE"].iloc[0] if "EVIDENCE_NATURE" in group.columns else "")
            ctrl_role = p_meta.get("CONTROL_ROLE") or (group["CONTROL_ROLE"].iloc[0] if "CONTROL_ROLE" in group.columns else "NONE")
            in_focus = p_meta.get("IN_MVA_FOCUS_COMPONENT") if "IN_MVA_FOCUS_COMPONENT" in p_meta else (group["IN_MVA_FOCUS_COMPONENT"].iloc[0] if "IN_MVA_FOCUS_COMPONENT" in group.columns else False)

            ranked_rows.append({
                "TARGET_SYMBOL": sym,
                "DRUG_NAME": drug_name,
                "AGGREGATED_SOURCES": ", ".join(sources),
                "NUM_SOURCES": len(sources),
                "MAX_CLINICAL_STAGE": max_stage,
                "APPROVED_ANY": approved_any,
                "DIRECTIONALITY_FIT": fit_status,
                "CONTRADICTION_FLAG": has_contradiction,
                "SAFETY_TIER": safety_tier,
                "INTERNAL_SCORE": score,
                "DIRECTIONALITY_EXPLANATION": group["DIRECTIONALITY_EXPLANATION"].iloc[0],
                "PEDIATRIC_HAZARD_NOTE": group["PEDIATRIC_HAZARD_NOTE"].iloc[0],
                "CLINICAL_RECOMMENDATION_STATUS": "PROHIBITED / INVESTIGATIONAL ONLY",
                "RESEARCH_ONLY_DISCLAIMER": RESEARCH_ONLY_DISCLAIMER,
                "GENE_CATEGORY": cat,
                "SELECTION_SOURCE": src,
                "EVIDENCE_NATURE": nature,
                "CONTROL_ROLE": ctrl_role,
                "IN_MVA_FOCUS_COMPONENT": in_focus,
            })

        ranking_df = pd.DataFrame(ranked_rows)
        # Sort so concordant / well-evidenced hypotheses appear first, and hazards appear at bottom
        ranking_df = ranking_df.sort_values(
            by=["INTERNAL_SCORE", "NUM_SOURCES", "APPROVED_ANY"],
            ascending=[False, False, False]
        ).reset_index(drop=True)
        ranking_df["RESEARCH_PRIORITY_RANK"] = ranking_df.index + 1
        ranking_df = ranking_df.drop(columns=["INTERNAL_SCORE"])
        return ranking_df

    def _build_mechanism_action_map(
        self,
        seed_genes: list[str],
        gene_context: dict[str, dict[str, Any]],
        matrix_df: pd.DataFrame,
    ) -> pd.DataFrame:
        """Build gene-level pathway mechanism to target action summary map."""
        map_rows: list[dict[str, Any]] = []
        for gene in seed_genes:
            ctx = gene_context.get(gene, {})
            p_meta = self.panel_metadata.get(gene, {})
            sub = matrix_df[matrix_df["TARGET_SYMBOL"] == gene] if not matrix_df.empty else pd.DataFrame()
            total_drugs = len(sub["DRUG_NAME"].unique()) if not sub.empty else 0
            approved_drugs = len(sub[sub["IS_APPROVED"]]["DRUG_NAME"].unique()) if not sub.empty else 0
            hazards = int((sub["DIRECTIONALITY_FIT"] == "MECHANISTIC_HAZARD").sum()) if not sub.empty else 0

            ot_rows = len(sub[sub["EVIDENCE_SOURCE"] == "Open Targets"]) if not sub.empty else 0
            chembl_rows = len(sub[sub["EVIDENCE_SOURCE"] == "ChEMBL"]) if not sub.empty else 0
            dgidb_rows = len(sub[sub["EVIDENCE_SOURCE"] == "DGIdb"]) if not sub.empty else 0
            rows_by_source = f"OPEN_TARGETS:{ot_rows};CHEMBL:{chembl_rows};DGIDB:{dgidb_rows}"

            if sub.empty:
                research_status = "NO_DRUG_EVIDENCE"
                primary_hazard = "No drug evidence retrieved across queried databases for this target."
            elif hazards > 0:
                research_status = "CONTRAINDICATED_PATHWAY_INHIBITORS_PRESENT"
                primary_hazard = f"Direct inhibition of {gene} worsens baseline checkpoint failure/instability."
            else:
                research_status = "NO_IMMEDIATE_DIRECTIONAL_HAZARDS"
                primary_hazard = "None identified in current database queries."

            cat = p_meta.get("GENE_CATEGORY") or ("CORE_MVA_CAUSAL" if gene in CANONICAL_MVA_SEEDS else "CANDIDATE")
            src = p_meta.get("SELECTION_SOURCE") or ("EXPERT_SEED" if gene in CANONICAL_MVA_SEEDS else "PHASE1")

            map_rows.append({
                "SEED_GENE": gene,
                "GENE_CATEGORY": cat,
                "SELECTION_SOURCE": src,
                "GENE_NAME": ctx.get("gene_name", p_meta.get("GENE_NAME", "Unassigned")),
                "PATHWAY": ctx.get("pathway", p_meta.get("PATHWAY", "Unassigned")),
                "BIOLOGICAL_ROLE": ctx.get("biological_role", p_meta.get("BIOLOGICAL_ROLE", "Unassigned")),
                "MVA_MECHANISM_LINK": ctx.get("mva_mechanism_link", p_meta.get("MVA_MECHANISM_LINK", "Secondary")),
                "CANONICAL_PATHWAY_DIRECTION": ctx.get("canonical_direction", p_meta.get("CANONICAL_PATHWAY_DIRECTION", "UNKNOWN")),
                "DESIRED_THERAPEUTIC_DIRECTION": ctx.get("therapeutic_direction", p_meta.get("THERAPEUTIC_DIRECTIONALITY", "UNKNOWN")),
                "TOTAL_DRUGS_IDENTIFIED": total_drugs,
                "APPROVED_DRUGS_COUNT": approved_drugs,
                "DIRECTIONAL_HAZARDS_COUNT": hazards,
                "PRIMARY_MECHANISTIC_HAZARD": primary_hazard,
                "DRUG_ROWS_BY_SOURCE": rows_by_source,
                "RESEARCH_STATUS": research_status,
            })
        return pd.DataFrame(map_rows)


def write_drug_evidence_outputs(
    evidence_matrix_df: pd.DataFrame,
    ranking_df: pd.DataFrame,
    action_map_df: pd.DataFrame,
    provenance: dict[str, Any],
    output_dir: Path,
    flat_names: bool = True,
) -> dict[str, Path]:
    """Write Phase 3 outputs adhering strictly to repository naming conventions."""
    output_dir.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}

    if flat_names:
        paths["matrix"] = output_dir / "14_phase3_drug_evidence_matrix.csv"
        paths["ranking"] = output_dir / "15_phase3_safety_ranking.csv"
        paths["action_map"] = output_dir / "16_phase3_mechanism_action_map.csv"
        paths["provenance"] = output_dir / "17_phase3_repurposing_provenance.json"
    else:
        paths["matrix"] = output_dir / "drug_evidence_matrix.csv"
        paths["ranking"] = output_dir / "safety_ranking.csv"
        paths["action_map"] = output_dir / "mechanism_action_map.csv"
        paths["provenance"] = output_dir / "phase3_repurposing_provenance.json"

    evidence_matrix_df.to_csv(paths["matrix"], index=False)
    ranking_df.to_csv(paths["ranking"], index=False)
    action_map_df.to_csv(paths["action_map"], index=False)

    with open(paths["provenance"], "w", encoding="utf-8") as f:
        json.dump(provenance, f, indent=2)

    logger.info("Phase 3 outputs successfully written to %s", output_dir)
    return paths
